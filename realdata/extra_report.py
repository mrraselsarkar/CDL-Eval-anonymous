"""Tables of the added baselines (bench_extra.py) next to the seasonal naive baseline and Chronos-2.

Reads the rev2 result files (results/rev2) and writes
  ../outputs/tables/rev2_extra.tex       24-step forecasts on the seven datasets: QL / coverage and rank correlations
  ../outputs/tables/rev2_extra_long.tex  192- and 720-step forecasts on the three held-out datasets
Scores are those of revision_report.setting_scores, averaged over the sampling seeds. CPU only.

  python extra_report.py
"""
import os

import numpy as np

os.environ["CUDA_VISIBLE_DEVICES"] = "-1"
import revision_report as rr  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
ROWS = [("naive", "", "Seasonal naive"), ("chronos2", "", "Chronos-2"), ("lagllama", "", "Lag-Llama"),
        ("lagllama", "ctx512", "Lag-Llama, context 512"), ("ets", "", "Exponential smoothing"),
        ("deepar", "", "DeepAR (trained)"), ("small512_ar", "", "AR, Gaussian head (trained, 512)"),
        ("small512_flow", "", "Full-window flow (trained, 512)")]
DS24 = rr.ALL24
DSHEAD = {"ercot": "ERCOT", "traffic": "Traffic", "ausel": "Aus.\\ 02--15", "aemo": "AEMO 26",
          "aemo_mid": "AEMO 16--19", "ausel_season": "Aus.\\ 02--15 Jan.--Sep.", "ercot2026": "ERCOT 26"}


def scores(st, ds, H, model, setting):
    runs = st.runs(ds, H, model, setting)
    if not runs:
        return None
    s = [rr.setting_scores(r) for r in runs]
    return {k: float(np.mean([x[k] for x in s if k in x])) for k in s[0]}


def cell_acc(v):
    return "--" if v is None else f"{v['ql']:.3f} / {100 * v['cov80']:.0f}"


def cell_dep(v):
    if v is None or "rho_model" not in v:
        return "--"
    return f"{v['rho_model']:.2f} / {v['rho_obs']:.2f}"


def write(name, tex):
    out = os.path.join(HERE, "..", "outputs", "tables", name)
    with open(out, "w", encoding="utf-8") as f:
        f.write(tex)
    print(f"written {out}")


def table24(st):
    res = {(m, s, ds): scores(st, ds, 24, m, s) for m, s, _ in ROWS for ds in DS24}
    body = [r"\multicolumn{8}{@{}l}{\textit{QL / coverage (\%) of the central 80\% interval}} \\"]
    body += [f"{lab} & " + " & ".join(cell_acc(res[m, s, ds]) for ds in DS24) + r" \\" for m, s, lab in ROWS]
    body += [r"\midrule", r"\multicolumn{8}{@{}l}{\textit{$\rho_{\mathrm{model}}$ / $\rho_{\mathrm{obs}}$, lag 1}} \\"]
    body += [f"{lab} & " + " & ".join(cell_dep(res[m, s, ds]) for ds in DS24) + r" \\" for m, s, lab in ROWS
             if m != "chronos2"]
    return "\n".join([
        "% generated by realdata/extra_report.py",
        r"\begin{table*}[!t]",
        r"\centering",
        r"\caption{Added Baselines, 24-Step Forecasts}",
        r"\label{tab:extra}",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{fitwidth}",           # defined in main.tex and supplementary.tex (printed in the main text)
        r"\begin{tabular}{@{}l c c c c c c c@{}}",
        r"\toprule",
        "Forecast & " + " & ".join(DSHEAD[d] for d in DS24) + r" \\",
        r"\midrule",
        *body,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{fitwidth}",
        "",
        r"\vspace{2pt}",
        r"\parbox{\textwidth}{\footnotesize The test windows are those of the foundation models, and scores are "
        r"averaged over three sampling seeds "
        r"(training seeds for the small forecasters). The AEMO and ERCOT 2026 windows use the model trained on the "
        r"held-out dataset of the same source. Chronos-2 and the naive baseline are included for comparison.}",
        r"\end{table*}",
        ""])


def table_long(st):
    dss = ["ercot", "traffic", "ausel"]
    cols = [(H, ds) for H in (192, 720) for ds in dss]
    rows = [r for r in ROWS if r[0] in ("naive", "chronos2", "lagllama", "ets", "deepar") and r[1] == ""]
    body = []
    for m, s, lab in rows:
        cells = [cell_acc(scores(st, ds, H, m, s)) for H, ds in cols]
        if any(c != "--" for c in cells):
            body.append(f"{lab} & " + " & ".join(cells) + r" \\")
    head = [r" & \multicolumn{3}{c}{$H = 192$} & \multicolumn{3}{c}{$H = 720$} \\",
            r"\cmidrule(lr){2-4}\cmidrule(l){5-7}",
            "Forecast & " + " & ".join(DSHEAD[ds] for _, ds in cols) + r" \\"]
    return "\n".join([
        "% generated by realdata/extra_report.py",
        r"\begin{table*}[!t]",
        r"\centering",
        r"\caption{Added Baselines at Longer Horizons: QL / Coverage (\%) of the Central 80\% Interval}",
        r"\label{stab:extralong}",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{fitwidth}",           # defined in supplementary.tex
        r"\begin{tabular}{@{}l c c c c c c@{}}",
        r"\toprule",
        *head,
        r"\midrule",
        *body,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{fitwidth}",
        "",
        r"\vspace{2pt}",
        r"\parbox{\textwidth}{\footnotesize 150 windows per dataset and horizon, one seed. Lag-Llama was limited to "
        r"24 steps (Section~\ref{snote:rev}).}",
        r"\end{table*}",
        ""])


def main():
    rr._colors()
    st = rr.Store(rr.rev2.REV2)
    write("rev2_extra.tex", table24(st))
    write("rev2_extra_long.tex", table_long(st))


if __name__ == "__main__":
    main()
