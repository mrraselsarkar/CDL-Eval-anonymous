"""Released update of the Sundial and Aurora flow heads against the probability-flow ODE, for a Gaussian target.

Both heads predict the clean target x1 from x_t = t x1 + (1 - t) x0, x0 ~ N(0, 1). The released samplers update
x <- x + (x1_hat - x0) / K with the initial noise x0, so that after K steps x is the average of the K predictions;
the ODE of the flow uses the velocity (x1_hat - x_t) / (1 - t). For x1 ~ N(0, s^2) the exact prediction is
E[x1 | x_t] = t s^2 x_t / (t^2 s^2 + (1 - t)^2). Prints the standard deviation of the samples relative to s
(1 for an exact sampler) for several s and K, and writes ../outputs/tables/gauss_sampler_table.tex. CPU only.

  python sampler_gauss.py
"""
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
SDS = [0.1, 0.3, 1.0, 3.0]
STEPS = [5, 50, 200]


def x1hat(x, t, s):
    return t * s ** 2 * x / (t ** 2 * s ** 2 + (1 - t) ** 2)


def ratios(s, K, n=200_000, seed=0):
    noise = np.random.default_rng(seed).standard_normal(n)
    xr, xo = noise.copy(), noise.copy()
    for i in range(K):
        t = i / K
        xr = xr + (x1hat(xr, t, s) - noise) / K               # released update
        xo = xo + (x1hat(xo, t, s) - xo) / (1 - t) / K         # velocity of the flow
    return xr.std() / s, xo.std() / s


def main():
    res = {(s, K): ratios(s, K) for s in SDS for K in STEPS}
    for s in SDS:
        print(f"target sd {s}: " + "; ".join(f"K={K}: released {res[s, K][0]:.2f}, ODE {res[s, K][1]:.2f}"
                                             for K in STEPS))
    rows = [f"{s:g} & " + " & ".join(f"{res[s, K][0]:.2f}" for K in STEPS) + " & "
            + " & ".join(f"{res[s, K][1]:.2f}" for K in STEPS) + r" \\" for s in SDS]
    tex = "\n".join([
        "% generated by realdata/sampler_gauss.py",
        r"\begin{table}[!t]",
        r"\centering",
        r"\caption{Spread of the Released Update and of the Flow ODE for a Gaussian Target}",
        r"\label{stab:gausssampler}",
        r"\small",
        r"\begin{tabular}{@{}r r r r r r r@{}}",
        r"\toprule",
        r" & \multicolumn{3}{c}{Released update, $K$ steps} & \multicolumn{3}{c}{Flow ODE, $K$ steps} \\",
        "Target SD & " + " & ".join(str(K) for K in STEPS) + " & " + " & ".join(str(K) for K in STEPS) + r" \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
        "",
        r"\vspace{2pt}",
        r"\parbox{\columnwidth}{\footnotesize Standard deviation of 200,000 samples divided by that of the target "
        r"$\mathcal{N}(0, s^2)$, with noise $\mathcal{N}(0, 1)$ and exact predictions of the target. Released update: "
        r"$\mathbf{x} \leftarrow \mathbf{x} + (\hat{\mathbf{x}}_1 - \mathbf{x}_0)/K$ with the initial noise "
        r"$\mathbf{x}_0$; flow ODE: Euler steps of the velocity $(\hat{\mathbf{x}}_1 - \mathbf{x}_t)/(1 - t)$.}",
        r"\end{table}",
        ""])
    out = os.path.join(HERE, "..", "outputs", "tables", "gauss_sampler_table.tex")
    with open(out, "w", encoding="utf-8") as f:
        f.write(tex)
    print(f"written {out}")


if __name__ == "__main__":
    main()
